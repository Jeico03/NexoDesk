using NexoDesk.Domain.Enums;

namespace NexoDesk.Domain.Entities;

public sealed class Ticket
{
    private Ticket()
    {
    }

    public Ticket(
        string title,
        string description,
        Guid categoryId,
        Guid requesterId,
        TicketPriority priority,
        DateTimeOffset createdAtUtc)
    {
        if (string.IsNullOrWhiteSpace(title))
        {
            throw new ArgumentException(
                "Ticket title is required.",
                nameof(title));
        }

        title = title.Trim();

        if (title.Length > 120)
        {
            throw new ArgumentException(
                "Ticket title cannot exceed 120 characters.",
                nameof(title));
        }

        if (string.IsNullOrWhiteSpace(description))
        {
            throw new ArgumentException(
                "Ticket description is required.",
                nameof(description));
        }

        if (categoryId == Guid.Empty)
        {
            throw new ArgumentException(
                "A valid category is required.",
                nameof(categoryId));
        }

        if (requesterId == Guid.Empty)
        {
            throw new ArgumentException(
                "A valid requester is required.",
                nameof(requesterId));
        }

        if (!Enum.IsDefined(priority))
        {
            throw new ArgumentOutOfRangeException(nameof(priority));
        }

        Id = Guid.NewGuid();

        Title = title;
        Description = description.Trim();

        CategoryId = categoryId;
        RequesterId = requesterId;

        Priority = priority;
        Status = TicketStatus.Open;

        CreatedAtUtc = createdAtUtc.ToUniversalTime();
    }

    public Guid Id { get; private set; }

    // Generated by the SQL Server sequence.
    public int Number { get; private set; }

    public string Title { get; private set; } = string.Empty;

    public string Description { get; private set; } = string.Empty;

    public Guid CategoryId { get; private set; }

    public TicketPriority Priority { get; private set; }
        = TicketPriority.Medium;

    public TicketStatus Status { get; private set; }
        = TicketStatus.Open;

    // User identifiers. Identity is implemented in Stage 3.
    public Guid RequesterId { get; private set; }

    public Guid? AssignedTechnicianId { get; private set; }

    public string? ResolutionSummary { get; private set; }

    public DateTimeOffset CreatedAtUtc { get; private set; }

    public DateTimeOffset? UpdatedAtUtc { get; private set; }

    public DateTimeOffset? ResolvedAtUtc { get; private set; }

    public DateTimeOffset? ClosedAtUtc { get; private set; }

    // SQL Server rowversion concurrency token.
    public byte[] RowVersion { get; private set; }
        = Array.Empty<byte>();

    public Category Category { get; private set; } = null!;

    public ICollection<TicketComment> Comments { get; private set; }
        = new List<TicketComment>();

    public ICollection<TicketHistory> History { get; private set; }
        = new List<TicketHistory>();

    // T-01 (Open -> Assigned) and T-02 (Reopened -> Assigned).
    public void AssignTechnician(
        Guid technicianId,
        DateTimeOffset updatedAtUtc)
    {
        if (technicianId == Guid.Empty)
        {
            throw new ArgumentException(
                "A valid technician is required.",
                nameof(technicianId));
        }

        if (Status is not (TicketStatus.Open or TicketStatus.Reopened) ||
            AssignedTechnicianId is not null)
        {
            throw new InvalidOperationException(
                "This ticket cannot be assigned in its current state.");
        }

        AssignedTechnicianId = technicianId;
        Status = TicketStatus.Assigned;

        UpdatedAtUtc = updatedAtUtc.ToUniversalTime();
    }

    // T-03 (Assigned / InProgress / WaitingForUser -> Assigned).
    public void ReassignTechnician(
        Guid technicianId,
        DateTimeOffset updatedAtUtc)
    {
        if (technicianId == Guid.Empty)
        {
            throw new ArgumentException(
                "A valid technician is required.",
                nameof(technicianId));
        }

        if (Status is not (TicketStatus.Assigned
                or TicketStatus.InProgress
                or TicketStatus.WaitingForUser) ||
            AssignedTechnicianId is null)
        {
            throw new InvalidOperationException(
                "This ticket cannot be reassigned in its current state.");
        }

        if (AssignedTechnicianId == technicianId)
        {
            throw new InvalidOperationException(
                "The ticket is already assigned to this technician.");
        }

        AssignedTechnicianId = technicianId;
        Status = TicketStatus.Assigned;

        UpdatedAtUtc = updatedAtUtc.ToUniversalTime();
    }

    public void ChangePriority(
        TicketPriority priority,
        DateTimeOffset updatedAtUtc)
    {
        if (!Enum.IsDefined(priority))
        {
            throw new ArgumentOutOfRangeException(nameof(priority));
        }

        if (Status == TicketStatus.Closed)
        {
            throw new InvalidOperationException(
                "A closed ticket cannot be modified.");
        }

        if (Priority == priority)
        {
            throw new InvalidOperationException(
                "The ticket already has this priority.");
        }

        Priority = priority;
        UpdatedAtUtc = updatedAtUtc.ToUniversalTime();
    }

    // T-04 (Assigned -> InProgress).
    public void StartProgress(DateTimeOffset updatedAtUtc)
    {
        if (Status != TicketStatus.Assigned ||
            AssignedTechnicianId is null)
        {
            throw new InvalidOperationException(
                "Only an assigned ticket can start progress.");
        }

        Status = TicketStatus.InProgress;
        UpdatedAtUtc = updatedAtUtc.ToUniversalTime();
    }

    // T-05 (InProgress -> WaitingForUser).
    public void WaitForUser(DateTimeOffset updatedAtUtc)
    {
        if (Status != TicketStatus.InProgress)
        {
            throw new InvalidOperationException(
                "Only an in-progress ticket can wait for the user.");
        }

        Status = TicketStatus.WaitingForUser;
        UpdatedAtUtc = updatedAtUtc.ToUniversalTime();
    }

    // T-06 (WaitingForUser -> InProgress).
    public void ResumeWork(DateTimeOffset updatedAtUtc)
    {
        if (Status != TicketStatus.WaitingForUser)
        {
            throw new InvalidOperationException(
                "Only a ticket waiting for the user can resume.");
        }

        Status = TicketStatus.InProgress;
        UpdatedAtUtc = updatedAtUtc.ToUniversalTime();
    }

    // T-07 (InProgress -> Resolved).
    public void RecordResolution(
        string resolutionSummary,
        DateTimeOffset resolvedAtUtc)
    {
        if (Status != TicketStatus.InProgress)
        {
            throw new InvalidOperationException(
                "Only an in-progress ticket can be resolved.");
        }

        if (string.IsNullOrWhiteSpace(resolutionSummary))
        {
            throw new ArgumentException(
                "Resolution summary is required.",
                nameof(resolutionSummary));
        }

        ResolutionSummary = resolutionSummary.Trim();

        ResolvedAtUtc = resolvedAtUtc.ToUniversalTime();
        Status = TicketStatus.Resolved;
        UpdatedAtUtc = ResolvedAtUtc;
    }

    // T-08 (Resolved -> Closed).
    public void Close(DateTimeOffset closedAtUtc)
    {
        if (Status != TicketStatus.Resolved)
        {
            throw new InvalidOperationException(
                "Only a resolved ticket can be closed.");
        }

        Status = TicketStatus.Closed;

        ClosedAtUtc = closedAtUtc.ToUniversalTime();
        UpdatedAtUtc = ClosedAtUtc;
    }

    // T-09 (Resolved -> Reopened). The ticket loses its technician and
    // its resolution, and must be assigned again (T-02).
    public void Reopen(DateTimeOffset updatedAtUtc)
    {
        if (Status != TicketStatus.Resolved)
        {
            throw new InvalidOperationException(
                "Only a resolved ticket can be reopened.");
        }

        Status = TicketStatus.Reopened;

        AssignedTechnicianId = null;
        ResolutionSummary = null;
        ResolvedAtUtc = null;
        UpdatedAtUtc = updatedAtUtc.ToUniversalTime();
    }
}